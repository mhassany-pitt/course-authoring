export function getLegacyCid(code?: string, name?: string): number | undefined {
  if (!code && !name) return undefined;
  const match = LEGACY_COURSES.find(
    (c) =>
      (code && name && c.code.toLowerCase() === code.toLowerCase() && c.name.toLowerCase() === name.toLowerCase()) ||
      (name && c.name.toLowerCase() === name.toLowerCase()) ||
      (code && c.code.toLowerCase() === code.toLowerCase())
  );
  return match?.cid;
}

export function getLegacyCourseByCid(cid: number | string): LegacyCourseMapping | undefined {
  const numCid = typeof cid === 'number' ? cid : parseInt(String(cid), 10);
  if (isNaN(numCid)) return undefined;
  return LEGACY_COURSES.find((c) => c.cid === numCid);
}

export function isCoursePorted(cid: number | string): boolean {
  const numCid = typeof cid === 'number' ? cid : parseInt(String(cid), 10);
  if (isNaN(numCid)) return false;
  return PORTED_CIDS.has(numCid);
}
